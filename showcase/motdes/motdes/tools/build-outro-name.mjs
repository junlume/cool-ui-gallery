/**
 * Compile the outro thank you message into individual SVG glyphs.
 *
 * Uses the existing Archivo font and fontkitten, like build-section-title.mjs.
 * Paths share a height-100 coordinate system, retaining the font's aspect
 * ratio and the spaces between words. No font loading is needed at run time.
 *
 *   node tools/build-outro-name.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { create } from 'fontkitten';

const TEXT = 'THANKS FOR WATCHING';
const WEIGHT = 600;
const TRACKING = 0.02;
const WORD_SPACING = 0.08;
const HEIGHT = 100;
const FONT = new URL('../node_modules/@fontsource-variable/archivo/files/archivo-latin-wght-normal.woff2', import.meta.url);
const font = create(new Uint8Array(readFileSync(FONT)));

// The installed font's default instance is 600. getVariation() is unsupported
// by this fontkitten build, so fail explicitly if that default ever changes.
if (font.variationAxes?.wght?.default !== WEIGHT) {
  throw new Error(`Expected Archivo default weight ${WEIGHT}, got ${font.variationAxes?.wght?.default}`);
}

const chars = [...TEXT];
const sourceGlyphs = font.glyphsForString(TEXT);
if (sourceGlyphs.length !== chars.length) {
  throw new Error('Expected a separate source glyph for every character.');
}

const tracking = TRACKING * font.unitsPerEm;
const raw = [];
let pen = 0;
let minX = Infinity; let minY = Infinity;
let maxX = -Infinity; let maxY = -Infinity;
sourceGlyphs.forEach((glyph, index) => {
  const ch = chars[index];
  // A space has no ink; its advance still separates the words.
  if (ch !== ' ') {
    const box = glyph.bbox;
    if (![box.minX, box.minY, box.maxX, box.maxY].every(Number.isFinite)) {
      throw new Error(`Non-finite font bounds for ${ch}`);
    }
    minX = Math.min(minX, pen + box.minX);
    maxX = Math.max(maxX, pen + box.maxX);
    minY = Math.min(minY, box.minY);
    maxY = Math.max(maxY, box.maxY);
    raw.push({ ch, glyph, pen, box });
  }
  pen += glyph.advanceWidth + tracking + (ch === ' ' ? WORD_SPACING * font.unitsPerEm : 0);
});

const scale = HEIGHT / (maxY - minY);
const f = (value) => Number(value.toFixed(3));
const width = f((maxX - minX) * scale);
const glyphs = raw.map(({ ch, glyph, pen: glyphX, box }) => ({
  ch,
  d: glyph.path.transform(scale, 0, 0, -scale, (glyphX - minX) * scale, maxY * scale).toSVG(),
  box: {
    x: f((glyphX + box.minX - minX) * scale),
    y: f((maxY - box.maxY) * scale),
    w: f((box.maxX - box.minX) * scale),
    h: f((box.maxY - box.minY) * scale),
  },
}));

if (glyphs.map(({ ch }) => ch).join('') !== TEXT.replace(/\s/g, '')) {
  throw new Error('Expected every non-space character to have a drawable glyph.');
}
const gaps = glyphs.slice(1).map((glyph, index) => {
  const previous = glyphs[index].box;
  return glyph.box.x - previous.x - previous.w;
});
glyphs.forEach(({ ch, d, box }) => {
  if (!Object.values(box).every(Number.isFinite) || box.w <= 0 || box.h <= 0
      || box.x < -0.002 || box.y < -0.002
      || box.x + box.w > width + 0.002 || box.y + box.h > HEIGHT + 0.002
      || !d || /NaN|Infinity/.test(d)) {
    throw new Error(`Invalid generated geometry for ${ch}`);
  }
});
if (gaps.some((gap) => gap <= 0)) throw new Error('Generated letter bounds overlap.');
const wordEnds = TEXT.split(' ').slice(0, -1).map((_, index, words) => words.slice(0, index + 1).join('').length - 1);
const wordGaps = gaps.filter((_, index) => wordEnds.includes(index));
const letterGaps = gaps.filter((_, index) => !wordEnds.includes(index));
if (wordGaps.some((gap) => gap <= Math.max(...letterGaps) * 2)) {
  throw new Error(`Word gaps must be visibly wider than letter spacing: ${JSON.stringify({ wordGaps, letterGaps })}`);
}

const output = `/**
 * Outro replacement glyphs — generated by tools/build-outro-name.mjs.
 * ${TEXT}; Archivo ${WEIGHT}; tracking ${TRACKING}em; word spacing ${WORD_SPACING}em.
 * Shared coordinates: width ${width}, height ${HEIGHT}; preserve this aspect ratio.
 */
export const OUTRO_NAME_TEXT = '${TEXT}';
export const OUTRO_NAME_WIDTH = ${width};
export const OUTRO_NAME_HEIGHT = ${HEIGHT};
export const OUTRO_NAME_GLYPHS = ${JSON.stringify(glyphs, null, 2)};
`;
writeFileSync(new URL('../src/lib/outro-name.js', import.meta.url), output);
console.log(JSON.stringify({ text: TEXT, glyphs: glyphs.length, width, height: HEIGHT,
  wordGaps: wordGaps.map(f), letterGapRange: [f(Math.min(...letterGaps)), f(Math.max(...letterGaps))],
  output: 'src/lib/outro-name.js' }));
